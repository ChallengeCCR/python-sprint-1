    ID_PASSAGEIRO INTEGER NOT NULL,
    CONSTRAINT FK_FEEDBACK_PASSAGEIRO FOREIGN KEY (ID_PASSAGEIRO)
        REFERENCES T_AUMO_PASSAGEIRO(ID_PASSAGEIRO)
        ON DELETE CASCADE
);

