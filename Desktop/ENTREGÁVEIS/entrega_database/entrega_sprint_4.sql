-- CREATE TABLES

-- Passageiro
CREATE TABLE T_AUMO_PASSAGEIRO (
    ID_PASSAGEIRO INTEGER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_AUMO_PASSAGEIRO PRIMARY KEY,
    DELETED NUMBER(1) DEFAULT 0,
    DT_CRIACAO TIMESTAMP NOT NULL,
    NM_PASSAGEIRO VARCHAR2(60) NOT NULL,
    EMAIL_PASSAGEIRO VARCHAR2(30) NOT NULL
);

-- Mensagem de contato (canal de suporte)
CREATE TABLE T_AUMO_MS_CONTATO (
    ID_CONTATO INTEGER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_AUMO_CONTATO PRIMARY KEY,
    DT_CRIACAO TIMESTAMP NOT NULL,
    MS_CONTATO VARCHAR2(255) NOT NULL,
    
    ID_PASSAGEIRO INTEGER NOT NULL,
    CONSTRAINT FK_CONTATO_PASSAGEIRO FOREIGN KEY (ID_PASSAGEIRO)
        REFERENCES T_AUMO_PASSAGEIRO(ID_PASSAGEIRO)
        ON DELETE CASCADE
);

-- Mensagem de feedback
CREATE TABLE T_AUMO_FEEDBACK (
    ID_FEEDBACK INTEGER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_AUMO_FEEDBACK PRIMARY KEY,
    DT_CRIACAO TIMESTAMP DEFAULT SYSDATE NOT NULL,
    MS_FEEDBACK VARCHAR2(255) NOT NULL,
    NV_SATISFACAO VARCHAR2(15) NOT NULL
