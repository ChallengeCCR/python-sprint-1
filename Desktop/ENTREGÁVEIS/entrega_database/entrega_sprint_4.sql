-- CREATE TABLES

-- Colaborador 
CREATE TABLE T_AUMO_COLABORADOR(
    ID_COLABORADOR INTEGER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_AUMO_COLABORADOR PRIMARY KEY,
    DELETED NUMBER(1) DEFAULT 0,
    DT_CRIACAO TIMESTAMP NOT NULL,
    NM_COLABORADOR VARCHAR2(60) NOT NULL,
    TP_COLABORADOR VARCHAR2(30) NOT NULL
);

-- Autentica colaborador
CREATE TABLE T_AUMO_AUTENTICA_COLABORADOR (
    ID_COLABORADOR INTEGER PRIMARY KEY,
    EMAIL VARCHAR2(60) UNIQUE NOT NULL,
    SENHA VARCHAR2(30) NOT NULL,
    CONSTRAINT FK_AUT_COLABORADOR FOREIGN KEY (ID_COLABORADOR)
        REFERENCES T_AUMO_COLABORADOR (ID_COLABORADOR) ON DELETE CASCADE
);


-- Sessão colaborador
CREATE TABLE T_AUMO_SESSAO_COLABORADOR(
    ID_SESSAO INTEGER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_AUMO_SESSAO PRIMARY KEY,
    ID_COLABORADOR INTEGER NOT NULL,
    TOKEN_SESSAO VARCHAR2(36) UNIQUE NOT NULL,
    DT_LOGIN TIMESTAMP NOT NULL,
    DT_LOGOUT TIMESTAMP,
    ST_SESSAO VARCHAR2(15) DEFAULT 'ATIVA'
        CONSTRAINT CHK_ST_SESSAO CHECK (ST_SESSAO IN ('ATIVA', 'INATIVA')),
    CONSTRAINT FK_SESSAO_COLABORADOR FOREIGN KEY (ID_COLABORADOR)
        REFERENCES T_AUMO_COLABORADOR (ID_COLABORADOR) ON DELETE CASCADE
);


-- Linha
CREATE TABLE T_AUMO_LINHA (
    ID_LINHA INTEGER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_AUMO_LINHA PRIMARY KEY,
    DELETED NUMBER(1) DEFAULT 0 NOT NULL,
    DT_CRIACAO TIMESTAMP NOT NULL,
    NM_LINHA VARCHAR2(60) NOT NULL, 
    NR_LINHA INTEGER NOT NULL,
    ST_LINHA VARCHAR2(15) CHECK (ST_LINHA IN ('NORMAL', 'PARCIAL', 'INTERROMPIDO')) NOT NULL
);


-- Estação
CREATE TABLE T_AUMO_ESTACAO (
    ID_ESTACAO INTEGER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_AUMO_ESTACAO PRIMARY KEY,
    ID_LINHA INTEGER NOT NULL,
    DELETED NUMBER(1) DEFAULT 0 NOT NULL,
    DT_CRIACAO TIMESTAMP NOT NULL, 
    NM_ESTACAO VARCHAR2(60) NOT NULL,   
    ST_ESTACAO VARCHAR2(15) NOT NULL
        CONSTRAINT CHK_ST_ESTACAO CHECK (ST_ESTACAO IN ('NORMAL', 'PARCIAL', 'INTERROMPIDO')),
    HR_FUNCIONAMENTO_INICIO DATE NOT NULL,  
    HR_FUNCIONAMENTO_FIM DATE NOT NULL, 
    CONSTRAINT FK_ESTACAO_LINHA FOREIGN KEY (ID_LINHA)
        REFERENCES T_AUMO_LINHA (ID_LINHA) ON DELETE CASCADE
);


-- Alerta
CREATE TABLE T_AUMO_ALERTA (
    ID_ALERTA INTEGER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_AUMO_ALERTA PRIMARY KEY,
    DELETED NUMBER(1) DEFAULT 0 NOT NULL,
    DT_CRIACAO TIMESTAMP NOT NULL,
    DT_ENCERRAMENTO TIMESTAMP,
    DS_ALERTA VARCHAR2(160) NOT NULL,
    NM_ALERTA VARCHAR2(255) NOT NULL,
    NV_GRAVIDADE VARCHAR2(15) NOT NULL
        CONSTRAINT CHK_NV_GRAVIDADE CHECK (NV_GRAVIDADE IN ('LEVE', 'MÉDIO', 'GRAVE')),
    ID_LINHA INTEGER NOT NULL,
    ID_ESTACAO INTEGER NOT NULL,
    CONSTRAINT FK_ALERTA_LINHA FOREIGN KEY (ID_LINHA)
        REFERENCES T_AUMO_LINHA (ID_LINHA) ON DELETE CASCADE,
    CONSTRAINT FK_ALERTA_ESTACAO FOREIGN KEY (ID_ESTACAO)
        REFERENCES T_AUMO_ESTACAO (ID_ESTACAO) ON DELETE CASCADE
);


-- Manutenção
CREATE TABLE T_AUMO_MANUTENCAO(
    ID_MANUTENCAO INTEGER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_AUMO_MANUTENCAO PRIMARY KEY,
    DELETED NUMBER(1) DEFAULT 0 NOT NULL,
    DT_CRIACAO TIMESTAMP NOT NULL,
    NM_MANUTENCAO VARCHAR2(60) NOT NULL,
    DS_MANUTENCAO VARCHAR2(255) NOT NULL,
    NV_PRIORIDADE VARCHAR2(15) NOT NULL
        CONSTRAINT CHK_NV_PRIORIDADE CHECK (NV_PRIORIDADE IN ('BAIXA', 'MÉDIA', 'ALTA')),
    ID_LINHA INTEGER NOT NULL,
    ID_ESTACAO INTEGER NOT NULL,
    CONSTRAINT FK_MANUTENCAO_ESTACAO FOREIGN KEY (ID_ESTACAO)
        REFERENCES T_AUMO_ESTACAO (ID_ESTACAO),
    CONSTRAINT FK_MANUTENCAO_LINHA FOREIGN KEY (ID_LINHA)
        REFERENCES T_AUMO_LINHA (ID_LINHA)
);


-- Log de atividade
CREATE TABLE T_AUMO_LOG_ATIVIDADE (
    ID_LOG_ATIVIDADE INTEGER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_LOG_ATIVIDADE PRIMARY KEY,
    TOKEN_SESSAO VARCHAR(36) NOT NULL,
    DT_CRIACAO TIMESTAMP NOT NULL,
    ACAO_REALIZADA VARCHAR2(120),
    CONSTRAINT FK_LOG_ATIVIDADE_TOKEN_SESSAO FOREIGN KEY (TOKEN_SESSAO)
        REFERENCES T_AUMO_SESSAO_COLABORADOR (TOKEN_SESSAO)
);


